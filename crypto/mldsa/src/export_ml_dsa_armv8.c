/*
 * The table is generated by following script:
 * def bit_reverse(a, k=8):
 *     """Computes k-bit reversal of a."""
 *     return int(format(a, f'0{k}b')[::-1], 2)
 * 
 * def get_barrett_pair(omega, q=8380417):
 *     """Precomputes (Root, Twisted) pair for Barrett multiplication."""
 *     # Canonical signed representative in [-q/2, q/2]
 *     if omega > q // 2:
 *         omega -= q
 *         
 *     # Twisted constant: round(omega * 2^31 / q) 
 *     # Used for Neon SQRDMULH doubling high-half logic
 *     r_half = 1 << 31
 *     twisted = (omega * r_half + q // 2) // q
 *     return [omega, twisted]
 * 
 * def split_ntt(inp):
 *     p1 = []
 *     for i in range(1, 5):
 *         p1.extend(inp[i])
 *     for i in range(5, 8):
 *         p1.extend(inp[i])
 *     p1.extend([0, 0])
 * 
 *     for k in range(1, 9):
 *         for i in [7+k, 14+2*k, 15+2*k, 28+4*k]:
 *             p1.extend(inp[i])
 *         for i in [29+4*k, 30+4*k, 31+4*k]:
 *             p1.extend(inp[i])
 *         p1.extend([0, 0])
 * 
 *     p2 = []
 *     for g in range(16):
 *         base_a = 64 + 4*g
 *         p2.extend([inp[base_a + j][0] for j in range(4)])
 *         p2.extend([inp[base_a + j][1] for j in range(4)])
 *         base_b = 128 + 8*g
 *         p2.extend([inp[base_b + 2*j][0] for j in range(4)])
 *         p2.extend([inp[base_b + 2*j][1] for j in range(4)])
 *         p2.extend([inp[base_b + 2*j + 1][0] for j in range(4)])
 *         p2.extend([inp[base_b + 2*j + 1][1] for j in range(4)])
 * 
 *     return p1, p2
 * 
 * def split_intt(inp):
 *     p1 = []
 *     for g in range(16):
 *         p1.extend(inp[16 + g])      # twiddle factor
 *         p1.extend([0, 0])
 *         p1.extend(inp[32 + 2*g])    # data pair A
 *         p1.extend(inp[33 + 2*g])    # data pair B
 * 
 *     p1.extend([0, 0])               # computed slot (NTT)
 *     for i in range(2, 16):
 *         p1.extend(inp[i])
 *     p1.extend([0, 0])
 *     p1[128:130] = [-294725, -75523344] # magic number
 * 
 *     p2 = []
 *     for g in range(16):
 *         base_a = 64 + 4*g
 *         p2.extend([inp[base_a + j][0] for j in range(4)])
 *         p2.extend([inp[base_a + j][1] for j in range(4)])
 *         base_b = 128 + 8*g
 *         p2.extend([inp[base_b + 2*j][0] for j in range(4)])
 *         p2.extend([inp[base_b + 2*j][1] for j in range(4)])
 *         p2.extend([inp[base_b + 2*j + 1][0] for j in range(4)])
 *         p2.extend([inp[base_b + 2*j + 1][1] for j in range(4)])
 * 
 *     return p1, p2
 * 
 * def generate_mldsa_ntt_tables(q = 8380417, zeta = 1753):
 *     # 1. Generate the 127 principal roots in bit-reversed order
 *     fwd_roots = [get_barrett_pair(pow(zeta, bit_reverse(i, 8), q)) \
 *                   for i in range(0, 256)]
 *     ntt_l123456, ntt_l78 = split_ntt(fwd_roots)
 * 
 *     # 2. Inverse NTT Table
 *     # INTT uses inverse roots: zeta^(512 - bit_reverse(i))
 *     inv_roots = [get_barrett_pair(pow(zeta, 512 - bit_reverse(i, 8), q)) for i in range(0, 300)]
 *     intt_l123456, intt_l78 = split_intt(inv_roots)
 * 
 *     return ntt_l123456, ntt_l78, intt_l123456, intt_l78
 * 
 * ntt_l123456, ntt_l78, intt_l123456, intt_l78 = generate_mldsa_ntt_tables()
 */

